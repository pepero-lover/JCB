    // Ported from Fathom's init_indices(): builds PawnFactorFile/PawnFactorRank
    // (and PawnIdx as a byproduct, needed later for real position encoding)
    // by walking PAWN_TWIST and accumulating combinatorial counts from Binomial.
    static {
        // --- file-encoding variant (enc == FILE_ENC) ---
        for (int i = 0; i < 6; i++) {
            long s = 0;
            for (int j = 0; j < 24; j++) {
                PAWN_IDX[0][i][j] = s;
                int square = (1 + (j % 6)) * 8 + (j / 6);
                s += SyzygyMaterial.binomial[i][PAWN_TWIST[0][square]];
                if ((j + 1) % 6 == 0) {
                    PAWN_FACTOR_FILE[i][j / 6] = s;
                    s = 0;
                }
            }
        }

        // --- rank-encoding variant (enc == RANK_ENC) ---
        for (int i = 0; i < 6; i++) {
            long s = 0;
            for (int j = 0; j < 24; j++) {
                PAWN_IDX[1][i][j] = s;
                int square = (1 + (j / 4)) * 8 + (j % 4);
                s += SyzygyMaterial.binomial[i][PAWN_TWIST[1][square]];
                if ((j + 1) % 4 == 0) {
                    PAWN_FACTOR_RANK[i][j / 4] = s;
                    s = 0;
                }
            }
        }
    }
